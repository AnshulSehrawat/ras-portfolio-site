# Builds web-sized media from the owner's assets folder.
# Run: python3 tools/build_media.py   (from the site folder; needs Pillow)
# Writes media/ads, media/archive, media/art and js/content/media.js.
# The private source map (which file became which slug) goes next to the overnight report, not into the site.
import json, os, re, sys
from pathlib import Path
from PIL import Image

SITE = Path(__file__).resolve().parent.parent
SRC = Path.home() / "WORK/personal website/assets"
PRIVATE_MAP = Path.home() / "dularii/overnight/2026-11-20/portfolio/media_source_map.json"

# brand word in the file name -> niche shown on the site (no brand names in site data)
NICHE = {"FITFLEX": "apparel", "CLASSICFIT": "apparel", "SWEATSET": "apparel", "BATCH": "apparel",
         "SELIAN": "supplements", "SERENITY": "spa + studio", "SERENITYSTUDIO": "spa + studio"}

# concept names that read well as captions (from the owner's own file names)
CONCEPTS = {
    "COST PER WEAR": "cost per wear", "SECOND DATE": "second date", "FIT VERDICT": "fit verdict",
    "MOGGED MY SON": "different league", "MEN_S FASHION": "start with the tee", "THIS IS NOT": "this is not",
    "PHOTOGRAPHIC RECOGNITION-SCENE STATICS": "recognition scenes", "THE PEAK MYTH": "the peak myth",
    "WRONG SUSPECT": "wrong suspect", "CREATION OF THE NEW MAN": "evolve beyond the cubicle",
    "PROTEIN SYNTHESIS": "protein works better", "INGREDIENTS CALLOUTS": "ingredient callouts",
    "90 DAYS DIFFERENCE": "90 days", "TESTMAXXXING": "test isn't low", "T-SHIRT TYPOGRAPHY": "upgrade your fit",
    "MOST WANTED": "what he wears", "NOT DAD BOD": "dad bod is a marketing word", "BUY3GET3": "buy 3 get 3",
    "B3G3FREE": "buy 3 get 3", "SKINRITUAL": "skin ritual", "AVATAR1": "content studio", "I USED TO BE GUY": "still in there",
}


def niche_of(name):
    up = name.upper()
    for k in sorted(NICHE, key=len, reverse=True):
        if k in up:
            return NICHE[k]
    return "other"


def concept_of(name):
    up = name.upper()
    for k, v in CONCEPTS.items():
        if k in up:
            return v
    return ""


def fmt_of(w, h):
    r = h / w
    return "9:16" if r > 1.6 else ("4:5" if r > 1.15 else ("1:1" if r > 0.9 else "wide"))


def save(im, out, width, q=80):
    im = im.copy()
    if im.width > width:
        im = im.resize((width, round(im.height * width / im.width)), Image.LANCZOS)
    out.parent.mkdir(parents=True, exist_ok=True)
    im.save(out, "WEBP", quality=q, method=6)
    return im.size


def main():
    private, data = {}, {"best": [], "archive": [], "art": []}
    best_dir, all_dir = SRC / "diary/ads/best", SRC / "diary/ads/all"
    best_names = sorted(p.name for p in best_dir.iterdir() if p.suffix.lower() in (".png", ".jpg"))
    for i, n in enumerate(best_names, 1):
        slug = f"b{i:02d}"
        im = Image.open(best_dir / n).convert("RGB")
        w, h = im.size
        save(im, SITE / f"media/ads/{slug}-s.webp", 560)
        sz = save(im, SITE / f"media/ads/{slug}.webp", 1200, 82)
        data["best"].append({"id": slug, "w": sz[0], "h": sz[1], "fmt": fmt_of(w, h),
                             "niche": niche_of(n), "concept": concept_of(n)})
        private[slug] = f"best/{n}"
    all_names = sorted(p.name for p in all_dir.iterdir() if p.suffix.lower() in (".png", ".jpg"))
    j = 0
    for n in all_names:
        if n in best_names:
            continue
        j += 1
        slug = f"x{j:03d}"
        im = Image.open(all_dir / n).convert("RGB")
        w, h = im.size
        save(im, SITE / f"media/archive/{slug}-s.webp", 480, 76)
        sz = save(im, SITE / f"media/archive/{slug}.webp", 1200, 80)
        data["archive"].append({"id": slug, "w": sz[0], "h": sz[1], "fmt": fmt_of(w, h), "niche": niche_of(n),
                                "concept": concept_of(n)})
        private[slug] = f"all/{n}"
    art_dir = SRC / "digital_art"
    art_names = sorted((p.name for p in art_dir.iterdir() if p.suffix.lower() == ".jpg"),
                       key=lambda s: int(re.findall(r"\d+", s)[0]))
    for n in art_names:
        k = int(re.findall(r"\d+", n)[0])
        slug = f"a{k:02d}"
        im = Image.open(art_dir / n).convert("RGB")
        save(im, SITE / f"media/art/{slug}-s.webp", 640, 80)
        sz = save(im, SITE / f"media/art/{slug}.webp", 1800, 84)
        data["art"].append({"id": slug, "w": sz[0], "h": sz[1]})
        private[slug] = f"digital_art/{n}"
    js = "// generated by tools/build_media.py: sizes and tags for every image. don't edit by hand.\n"
    js += "export const media = " + json.dumps(data, indent=1) + ";\n"
    (SITE / "js/content/media.js").write_text(js)
    PRIVATE_MAP.write_text(json.dumps(private, indent=1))
    print(len(data["best"]), len(data["archive"]), len(data["art"]))


if __name__ == "__main__":
    sys.exit(main())
