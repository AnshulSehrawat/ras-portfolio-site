# Placeholders + AVIF copies for every photo on the site.
# Run: python3 tools/build_previews.py   (from the site folder; needs Pillow with AVIF)
# - media/{ads,archive,art}/<id>[-s].avif next to each .webp (about half the bytes; the site uses them when the
#   browser can show AVIF, else the .webp)
# - js/content/previews.js: per image a tiny blurred preview (data URI) and its average tone, shown under the photo
#   until it has loaded, so no image is ever an empty box
import base64, io, json, sys
from pathlib import Path
from PIL import Image

SITE = Path(__file__).resolve().parent.parent
MEDIA = SITE / "media"
force = "--force" in sys.argv


def tiny(im):
    t = im.convert("RGB")
    t.thumbnail((20, 20), Image.LANCZOS)
    b = io.BytesIO()
    t.save(b, "WEBP", quality=45, method=6)
    avg = t.resize((1, 1), Image.BOX).getpixel((0, 0))
    return "data:image/webp;base64," + base64.b64encode(b.getvalue()).decode(), "#%02x%02x%02x" % avg


out, n_avif, web_b, avif_b = {}, 0, 0, 0
for d in ("ads", "archive", "art"):
    for f in sorted((MEDIA / d).glob("*.webp")):
        a = f.with_suffix(".avif")
        if force or not a.exists() or a.stat().st_mtime < f.stat().st_mtime:
            Image.open(f).convert("RGB").save(a, "AVIF", quality=62, speed=6)
            n_avif += 1
        web_b += f.stat().st_size; avif_b += a.stat().st_size
        if f.stem.endswith("-s"):
            out[f.stem[:-2]] = tiny(Image.open(f))
for f in sorted((MEDIA / "gate").glob("*.webp")):
    out["gate/" + f.stem] = tiny(Image.open(f))

js = ("// generated by tools/build_previews.py: id -> [tiny blurred preview, average tone]. don't edit by hand.\n"
      "export const previews = " + json.dumps(out, separators=(",", ":")) + ";\n")
(SITE / "js/content/previews.js").write_text(js)
print(f"{len(out)} previews ({len(js) // 1024} KB js), {n_avif} avif written; webp {web_b >> 20} MB -> avif {avif_b >> 20} MB")
